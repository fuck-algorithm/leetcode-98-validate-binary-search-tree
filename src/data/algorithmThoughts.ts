export const algorithmThoughts = `## 解法：递归传递上下界

### 为什么不能只比较父子节点？
节点必须同时满足所有祖先施加的限制。比如输入 [5,1,4,null,null,3,6] 中，3 是根节点 5 的右子树节点，即使它小于父节点 4，仍然违反了“必须大于 5”的规则。

### 核心想法
对每个节点维护一个**开区间** (lower, upper)：
- 当前值必须满足 lower < node.val < upper；等于边界也不合法。
- 进入左子树时收紧上界：(lower, node.val)。
- 进入右子树时收紧下界：(node.val, upper)。
- 空节点表示这条分支没有违反规则，返回 true。

根节点从 (-∞, +∞) 开始，因此任意 32 位整数都能正确处理。

### 执行顺序
1. 检查当前节点是否为空。
2. 用它继承到的上下界检查节点值。
3. 递归验证左子树，再验证右子树；任一分支失败就提前返回。
4. 两个分支都通过，当前子树才有效。

### 复杂度
- 时间：O(n)，最坏每个节点访问一次；发现违规时会提前结束。
- 空间：O(h)，由递归深度决定；最坏退化树为 O(n)。`